#!/usr/bin/env python3
"""Subset existing LVGL uncompressed Montserrat bitmaps; deterministic, no downloads."""
import re
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
SOURCE=ROOT/'third_party/xiaozhi-esp32/managed_components/lvgl__lvgl/src/font'
OUT=ROOT/'firmware/mars_system/components/mars_canvas/round_fonts.h'
def main():
    out=['/* Generated by scripts/generate_round_fonts.py from bundled LVGL 9.5.0 Montserrat. */',
         '/* Retains upstream font bitmaps. See FONT-LICENSE.txt and source attribution. */',
         '#pragma once', 'typedef struct { unsigned offset; unsigned short advance; unsigned char w,h; signed char x,y; } mc_glyph_t;']
    for size in (16,20,48):
        s=(SOURCE/f'lv_font_montserrat_{size}.c').read_text()
        bitmap=s[s.index('glyph_bitmap[] = {'):s.index('static const lv_font_fmt_txt_glyph_dsc_t')]
        bitmap=re.sub(r'/\*.*?\*/','',bitmap,flags=re.S)
        data=bytes(int(v,16) for v in re.findall(r'0x([0-9a-fA-F]+)',bitmap))
        desc=s[s.index('glyph_dsc[] = {'):s.index('/*---------------------',s.index('glyph_dsc[] = {'))]
        glyphs=[tuple(map(int,m)) for m in re.findall(r'\.bitmap_index = (\d+), \.adv_w = (\d+), \.box_w = (\d+), \.box_h = (\d+), \.ofs_x = (-?\d+), \.ofs_y = (-?\d+)',desc)]
        packed=bytearray(); entries=[]
        for cp in range(32,127):
            index,adv,w,h,x,y=glyphs[cp-31]
            if size==48 and chr(cp) not in '0123456789:-': w=h=adv=x=y=0
            entries.append((len(packed),adv,w,h,x,y));packed+=data[index:index+(w*h+1)//2]
        out.append(f'static const unsigned char mc_font_{size}[] = {{')
        for i in range(0,len(packed),24):out.append(','.join(str(b) for b in packed[i:i+24])+',')
        out+=['};',f'static const mc_glyph_t mc_glyph_{size}[95] = {{']
        out += ['{'+','.join(map(str,g))+'},' for g in entries];out+=['};']
    OUT.write_text('\n'.join(out)+'\n')
    print(OUT)
if __name__=='__main__':main()
